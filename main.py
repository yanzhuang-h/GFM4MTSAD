"""GFM4MTSAD two-stage warm-start training and fixed-reference evaluation."""
import argparse
import json
from pathlib import Path
from training.assets import SPECS, ROOT, load_assets, verify_assets


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('command', choices=('check', 'pretrain', 'train', 'run', 'evaluate'))
    p.add_argument('--entity', choices=sorted({e for _, e in SPECS}), required=True)
    p.add_argument('--backend', choices=('anomalygfm', 'owleye'), required=True)
    p.add_argument('--assets', type=Path, required=True, help='JSON of external paths; relative paths resolve beside this file')
    p.add_argument('--seed', type=int, default=0)
    p.add_argument('--device', default='cuda:0', choices=('cuda:0', 'cpu'))
    p.add_argument('--threads', type=int, default=2)
    p.add_argument('--output', type=Path, help='New output directory; existing directories are never overwritten')
    p.add_argument('--frontend-registration', type=Path, help='Required for train; generated by pretrain')
    p.add_argument('--run-dir', type=Path, help='Completed joint-training directory for evaluate')
    args = p.parse_args(argv)
    if args.seed < 0 or args.threads < 1:
        p.error('seed must be nonnegative and threads must be positive')
    if args.command != 'check' and args.output is None:
        p.error('--output is required')
    if args.command == 'train' and args.frontend_registration is None:
        p.error('train requires --frontend-registration')
    if args.command == 'evaluate' and args.run_dir is None:
        p.error('evaluate requires --run-dir')
    return args


def main():
    args = parse_args()
    args.assets = load_assets(args.assets)
    checks = verify_assets(args.assets, args.backend, args.entity)
    if args.command == 'check':
        print(json.dumps(checks, indent=2))
        return
    from training.pipeline import execute
    execute(args)


if __name__ == '__main__':
    main()
